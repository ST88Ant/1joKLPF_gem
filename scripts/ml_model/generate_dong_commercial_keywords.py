def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.abspath(os.path.join(script_dir, "..", ".."))
    
    # 후보 경로 확인
    candidate_inputs = [
        os.path.join(project_root, "data", "processed", "mbti_행정동_2025Q4.csv"),
        os.path.join(script_dir, "..", "data", "mbti_행정동_2025Q4.csv"),
        "data/processed/mbti_행정동_2025Q4.csv"
    ]
    
    base_path = None
    for cand in candidate_inputs:
        if os.path.exists(cand):
            base_path = cand
            break
            
    if not base_path:
        print("Error: mbti_행정동_2025Q4.csv not found.")
        return

    df = pd.read_csv(base_path, encoding='utf-8-sig')
    print(f"Loaded {len(df)} rows from {base_path}")

    # 상권 분석 및 키워드 생성
    profile_df = df.apply(classify_dong_commercial_profile, axis=1)

    # 최종 컬럼 정렬: 기존 행정동 메타정보 + 상권 분석 키워드 컬럼
    meta_cols = ['자치구', '행정동_코드', '행정동_코드_명', '금융MBTI', '군집']
    if '아파트_평균_시가' in df.columns:
        meta_cols.append('아파트_평균_시가')
    if '1인가구비율' in df.columns:
        meta_cols.append('1인가구비율')
    if '청년인구비율' in df.columns:
        meta_cols.append('청년인구비율')

    result_df = pd.concat([df[meta_cols], profile_df], axis=1)

    # Gemi_pjt/data 및 루트 data/processed 둘 다 저장
    out_paths = [
        os.path.join(script_dir, "..", "data", "서울시_행정동별_상권분석_키워드.csv"),
        os.path.join(project_root, "data", "processed", "서울시_행정동별_상권분석_키워드.csv")
    ]
    
    for out_path in out_paths:
        os.makedirs(os.path.dirname(out_path), exist_ok=True)
        result_df.to_csv(out_path, index=False, encoding='utf-8-sig')
        print(f"Saved -> {out_path}")

if __name__ == '__main__':
    main()
