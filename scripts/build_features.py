# -*- coding: utf-8 -*-
"""
Step 2. 금융 건전성 파생지표 + 분기별 Z-score 상대지수

주의: SKT '요금 연체 비율'은 원자료에 2배 레벨 시프트가 있다
      (2023: 1·5~8·12월 ≈6.7 / 2~4·9~11월 ≈13.5-14.4, 2025.03도 동일 현상).
      동별 순위는 레짐이 바뀌어도 보존되므로(Spearman ρ=0.886, 동일 레짐 내 0.984)
      분기 내 Z-score로 표준화하면 레벨 시프트가 완전히 상쇄된다.
      => 모든 지표는 '분기 내 상대지수'로만 사용한다. 절대수준 시계열 비교 금지.
"""
import warnings; warnings.filterwarnings("ignore")
from pathlib import Path
import pandas as pd, numpy as np

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT/"data"/"processed"
p = pd.read_csv(OUT/"panel_행정동_분기_2023_2025.csv", encoding="utf-8-sig")

# ---------------------------------------------------------------- 파생지표
# 분모는 SKT 총인구를 쓴다.
# 상권분석 상주인구/가구수는 재건축 지역에서 갱신이 크게 늦다
#   (둔촌1동 상주인구 16명 vs SKT 22,127명 — 올림픽파크포레온 입주 미반영,
#    개포1동 6,765 vs 19,178, 반포본동 117 vs 4,325).
# 전체 상관은 r=0.941로 높지만 꼬리가 망가져 비율 분모로는 부적합하다.
p["청년인구비율"]   = p["청년_인구"] / p["SKT_총인구"]
p["1인가구비율"]    = p["SKT_1인가구수"] / p["SKT_총인구"]
p["청년1인가구비율"] = p["청년_1인가구수"] / p["SKT_총인구"]
p["인구갱신괴리"]   = p["총_상주인구_수"] / p["SKT_총인구"]      # 1에서 멀수록 상권분석 인구가 낡음
p["아파트가구비율"]  = p["아파트_가구_수"] / p["총_가구_수"]
p["재정관심도"]     = p["재정관심집단"] / p["재정관심_인구"]

# 기획서 Step2: 소득 대비 소비 비율 (소액결제=거주자 소비 대리지표)
p["소득대비소비"]   = p["소액결제_사용금액"] / (p["평균소득월액"] / 1000)
# 부채 데이터 부재 → 연체비율이 '소득 대비 상환부담'의 발현 형태
p["소득대비연체"]   = p["연체비율"] / (p["평균소득월액"] / 1_000_000)
p["자산_log"]      = np.log(p["아파트_평균_시가"].replace(0, np.nan))
p["상권활력"]      = p["지출_총금액"] / p["집객시설_수"].replace(0, np.nan)

# ------------------------------------------------- 분기 내 Z-score (레벨 시프트 상쇄)
ZCOLS = ["평균소득월액", "자산_log", "소액결제_사용금액", "연체비율", "청년_연체비율",
         "1인가구비율", "청년1인가구비율", "청년인구비율",
         "소득대비소비", "소득대비연체", "재정관심도", "상권활력"]
for c in ZCOLS:
    g = p.groupby("분기")[c]
    p[f"Z_{c}"] = (p[c] - g.transform("mean")) / g.transform("std")

p.to_csv(OUT/"features_행정동_분기_2023_2025.csv", index=False, encoding="utf-8-sig")
print(f"저장: features_행정동_분기_2023_2025.csv  ({len(p)}행 × {p.shape[1]}컬럼)")

chk = p.groupby("분기")[["Z_연체비율", "Z_소액결제_사용금액"]].agg(["mean", "std"]).round(3)
print("\n분기별 Z-score 검증 (평균 0 / 표준편차 1이어야 함)")
print(chk.head(4).to_string())
print("\n2025Q4 파생지표 요약")
q = p[p.분기 == 20254]
print(q[["청년인구비율","1인가구비율","청년1인가구비율","소득대비소비","소득대비연체","재정관심도","인구갱신괴리"]]
      .describe().T[["mean","std","min","50%","max"]].to_string(float_format=lambda x: f"{x:,.3f}"))
